// Reference-vector generator for s2rst CellUnion differential tests, using the C++
// reference implementation (google/s2geometry) as the oracle. Emits CSV that
// core/tests/cpp_cellunion_diff.rs diffs the Rust CellUnion implementation against, and
// that verify/tests/union_spec_vs_cpp.rs checks the verification model against
// (specs/002-formal-verify-cell-union, data-model §10). Deterministic (fixed seed). See
// tools/refgen-cpp/README.md.
//
// Ids are 16 lowercase hex digits; a list of ids is ';'-separated (empty field for an empty
// list); bytes are lowercase hex; booleans are 0/1.

#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <random>
#include <string>
#include <utility>
#include <vector>

#include "s2/s2cell_id.h"
