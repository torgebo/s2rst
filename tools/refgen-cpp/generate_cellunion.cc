namespace {

std::mt19937_64 rng(0x43554E49ULL);  // "CUNI"
std::normal_distribution<double> gauss(0.0, 1.0);

S2Point RandPoint() {
  S2Point p(gauss(rng), gauss(rng), gauss(rng));
  return p.Normalize();
}

// A random cell at `level`.
S2CellId RandCellAt(int level) { return S2CellId(RandPoint()).parent(level); }

// A random descendant of `anchor`, 0..4 levels below it (never below level 30).
S2CellId RandDescendant(S2CellId anchor) {
  int depth = static_cast<int>(rng() % 5);
  S2CellId c = anchor;
  for (int k = 0; k < depth && c.level() < S2CellId::kMaxLevel; ++k) {
    c = c.child(static_cast<int>(rng() % 4));
  }
  return c;
}

// 0..max_cells cells among `anchor`'s descendants: unsorted, with duplicates, nesting and
// (often) sibling groups. Every cell is valid, as upstream Normalize requires.
std::vector<S2CellId> RandCellsAround(S2CellId anchor, int max_cells) {
  std::vector<S2CellId> ids;
  int n = static_cast<int>(rng() % (max_cells + 1));
  for (int i = 0; i < n; ++i) ids.push_back(RandDescendant(anchor));
  if (n > 0 && rng() % 3 == 0 && !anchor.is_leaf()) {
    S2CellId p = RandDescendant(anchor);
    if (!p.is_leaf()) {
      for (int k = 0; k < 4; ++k) ids.push_back(p.child(k));
    }
  }
  return ids;
}

S2CellId RandAnchor(int min_level, int max_level) {
  int level = min_level + static_cast<int>(rng() % (max_level - min_level + 1));
  return RandCellAt(level);
}

std::string Hex64(uint64_t x) {
  char buf[17];
  std::snprintf(buf, sizeof buf, "%016llx", static_cast<unsigned long long>(x));
  return buf;
}

std::string Ids(const std::vector<S2CellId>& ids) {
  std::string out;
  for (size_t i = 0; i < ids.size(); ++i) {
    if (i > 0) out += ';';
    out += Hex64(ids[i].id());
  }
  return out;
}

std::string HexBytes(const std::string& s) {
  static const char kDigits[] = "0123456789abcdef";
  std::string out;
  for (unsigned char c : s) {
    out += kDigits[c >> 4];
    out += kDigits[c & 15];
  }
  return out;
}

void PutLe64(std::string* s, uint64_t x) {
  for (int k = 0; k < 8; ++k) s->push_back(static_cast<char>((x >> (8 * k)) & 0xff));
}

// A hand-built encoding: version byte, count, then the raw ids.
std::string RawEncoding(unsigned char version, uint64_t count, const std::vector<uint64_t>& ids) {
  std::string s(1, static_cast<char>(version));
  PutLe64(&s, count);
  for (uint64_t id : ids) PutLe64(&s, id);
  return s;
}

std::vector<uint64_t> Raw(const std::vector<S2CellId>& ids) {
  std::vector<uint64_t> out;
  for (S2CellId c : ids) out.push_back(c.id());
  return out;
}

std::string Encode(const S2CellUnion& u) {
  Encoder encoder;
  u.Encode(&encoder);
  return std::string(encoder.base(), encoder.length());
}

// A valid union that is not normalised: a normalised one with its first non-leaf cell
// replaced by its four children (unchanged if every cell is a leaf).
std::vector<S2CellId> SplitOne(const std::vector<S2CellId>& norm) {
  std::vector<S2CellId> out;
  bool done = false;
  for (S2CellId c : norm) {
    if (!done && !c.is_leaf()) {
      for (int k = 0; k < 4; ++k) out.push_back(c.child(k));
      done = true;
    } else {
      out.push_back(c);
    }
  }
  return out;
}

// The three children of `p` before its last one, then the four children of its last child:
// valid, and normalising it collapses twice (a cascade).
std::vector<S2CellId> CascadeOfSeven(S2CellId p) {
  std::vector<S2CellId> ids = {p.child(0), p.child(1), p.child(2)};
  for (int k = 0; k < 4; ++k) ids.push_back(p.child(3).child(k));
  return ids;
}

}  // namespace

int main() {
  std::printf(
      "# Generated by tools/refgen-cpp/generate_cellunion (oracle: google/s2geometry). "
      "Do not edit by hand.\n");

  // input ids (any order, valid cells) -> S2CellUnion(input).cell_ids().
  std::printf("# CELLUNION_NORMALIZE\n");
  {
    std::vector<std::vector<S2CellId>> inputs;
    for (int f = 0; f < 6; ++f) {
      S2CellId face = S2CellId::FromFace(f);
      inputs.push_back({face.child(0), face.child(1), face.child(2), face.child(3)});
    }
    inputs.push_back(CascadeOfSeven(RandCellAt(12)));
    {
      S2CellId c = RandCellAt(9);
      inputs.push_back({c.child(2).child(1), c});
      inputs.push_back({c, c.child(3), c});
    }
    {
      std::vector<S2CellId> faces;
      for (int f = 5; f >= 0; --f) faces.push_back(S2CellId::FromFace(f));
      inputs.push_back(faces);
    }
    inputs.push_back({});
    for (int i = 0; i < 300; ++i) inputs.push_back(RandCellsAround(RandAnchor(0, 20), 8));
    for (const auto& in : inputs) {
      S2CellUnion u(in);
      std::printf("%s,%s\n", Ids(in).c_str(), Ids(u.cell_ids()).c_str());
    }
  }

  // normalised input ids, min_level, level_mod -> Denormalize(min_level, level_mod).
  // Every row keeps each cell's level gap at 2 or less, so outputs stay at 16 cells per input
  // cell; that covers every combination FR-015 names (levels 29 and 30 with level_mod 2, 3).
  std::printf("# CELLUNION_DENORMALIZE\n");
  {
    for (int min_level = 0; min_level <= S2CellId::kMaxLevel; ++min_level) {
      for (int level_mod = 1; level_mod <= 3; ++level_mod) {
        for (int level = 0; level <= S2CellId::kMaxLevel; ++level) {
          if (std::max(min_level, level) - level > 2) continue;
          S2CellUnion u(std::vector<S2CellId>{RandCellAt(level)});
          std::vector<S2CellId> out;
          u.Denormalize(min_level, level_mod, &out);
          std::printf("%s,%d,%d,%s\n", Ids(u.cell_ids()).c_str(), min_level, level_mod,
                      Ids(out).c_str());
        }
      }
    }
    for (int i = 0; i < 200; ++i) {
      int min_level = static_cast<int>(rng() % 31);
      int level_mod = 1 + static_cast<int>(rng() % 3);
      S2CellId anchor = RandAnchor(std::max(0, min_level - 2), S2CellId::kMaxLevel);
      S2CellUnion u(RandCellsAround(anchor, 6));
      std::vector<S2CellId> out;
      u.Denormalize(min_level, level_mod, &out);
      std::printf("%s,%d,%d,%s\n", Ids(u.cell_ids()).c_str(), min_level, level_mod,
                  Ids(out).c_str());
    }
  }

  // a, b (normalised) -> Union, Intersection, Difference, Contains(b), Intersects(b).
  std::printf("# CELLUNION_SETOPS\n");
  {
    std::vector<std::pair<S2CellUnion, S2CellUnion>> pairs;
    for (int i = 0; i < 300; ++i) {
      S2CellId anchor = RandAnchor(0, 20);
      S2CellUnion a(RandCellsAround(anchor, 8));
      S2CellId b_anchor = (i % 2 == 0) ? anchor : RandAnchor(0, 20);
      S2CellUnion b(RandCellsAround(b_anchor, 8));
      pairs.emplace_back(a, b);
    }
    S2CellUnion some(RandCellsAround(RandAnchor(0, 10), 8));
    pairs.emplace_back(S2CellUnion(), some);
    pairs.emplace_back(some, S2CellUnion());
    pairs.emplace_back(S2CellUnion::WholeSphere(), some);
    pairs.emplace_back(some, S2CellUnion::WholeSphere());
    for (const auto& [a, b] : pairs) {
      std::printf("%s,%s,%s,%s,%s,%d,%d\n", Ids(a.cell_ids()).c_str(), Ids(b.cell_ids()).c_str(),
                  Ids(a.Union(b).cell_ids()).c_str(), Ids(a.Intersection(b).cell_ids()).c_str(),
                  Ids(a.Difference(b).cell_ids()).c_str(), a.Contains(b) ? 1 : 0,
                  a.Intersects(b) ? 1 : 0);
    }
  }

  // begin, end (leaves or End(30), begin <= end) -> FromBeginEnd(begin, end).
  std::printf("# CELLUNION_FROM_BEGIN_END\n");
  {
    const S2CellId leaf_end = S2CellId::End(S2CellId::kMaxLevel);
    std::vector<std::pair<S2CellId, S2CellId>> ranges;
    ranges.emplace_back(S2CellId::Begin(S2CellId::kMaxLevel), leaf_end);
    S2CellId x = RandCellAt(30);
    ranges.emplace_back(x, x);
    ranges.emplace_back(x, x.next());
    ranges.emplace_back(S2CellId::FromFace(0).range_max().advance(-1000),
                        S2CellId::FromFace(1).range_min().advance(1000));
    for (int i = 0; i < 3; ++i) ranges.emplace_back(RandCellAt(30), leaf_end);
    for (int i = 0; i < 100; ++i) {
      S2CellId a = RandCellAt(30), b = RandCellAt(30);
      if (b < a) std::swap(a, b);
      ranges.emplace_back(a, b);
    }
    for (int i = 0; i < 200; ++i) {
      S2CellId b = RandCellAt(30);
      int64_t k = static_cast<int64_t>(rng() % (uint64_t{1} << 24));
      S2CellId e = b.advance(k);  // advance clamps at End(30)
      ranges.emplace_back(b, e);
    }
    for (const auto& [b, e] : ranges) {
      std::printf("%s,%s,%s\n", Hex64(b.id()).c_str(), Hex64(e.id()).c_str(),
                  Ids(S2CellUnion::FromBeginEnd(b, e).cell_ids()).c_str());
    }
  }

  // The unions for LEAF_CELLS and ENCODE: normalised ones, then valid non-normalised ones.
  std::vector<S2CellUnion> unions;
  for (int i = 0; i < 200; ++i) unions.push_back(S2CellUnion(RandCellsAround(RandAnchor(0, 20), 8)));
  for (int i = 0; i < 100; ++i) {
    S2CellUnion norm(RandCellsAround(RandAnchor(0, 20), 8));
    unions.push_back(S2CellUnion::FromVerbatim(SplitOne(norm.cell_ids())));
  }
  unions.push_back(S2CellUnion::WholeSphere());

  // ids (valid) -> LeafCellsCovered().
  std::printf("# CELLUNION_LEAF_CELLS\n");
  for (const S2CellUnion& u : unions) {
    std::printf("%s,%llu\n", Ids(u.cell_ids()).c_str(),
                static_cast<unsigned long long>(u.LeafCellsCovered()));
  }

  // ids (valid) -> Encode() bytes.
  std::printf("# CELLUNION_ENCODE\n");
  for (const S2CellUnion& u : unions) {
    std::printf("%s,%s\n", Ids(u.cell_ids()).c_str(), HexBytes(Encode(u)).c_str());
  }

  // bytes -> Decode() result, IsValid() of the decoded union, and the decoded ids. C++
  // validates nothing, so it accepts unsorted, duplicate, overlapping and invalid ids
  // (ok = 1, valid = 0): that is U-003.
  std::printf("# CELLUNION_DECODE\n");
  {
    std::vector<std::string> inputs;
    for (const S2CellUnion& u : unions) inputs.push_back(Encode(u));
    S2CellId p = RandCellAt(11);
    inputs.push_back(RawEncoding(1, 4, Raw({p.child(0), p.child(1), p.child(2), p.child(3)})));
    inputs.push_back(RawEncoding(1, 7, Raw(CascadeOfSeven(RandCellAt(7)))));
    {
      S2CellId c = RandCellAt(5);
      std::string three = RawEncoding(1, 3, Raw({c.child(0), c.child(2), c.child(3)}));
      for (size_t len : {0, 1, 8, 9, 16, 24}) inputs.push_back(three.substr(0, len));
      inputs.push_back(RawEncoding(0, 3, Raw({c.child(0), c.child(2), c.child(3)})));
      inputs.push_back(RawEncoding(2, 0, {}));
      inputs.push_back(RawEncoding(2, 1, Raw({c})));
      inputs.push_back(RawEncoding(1, 1000001, {}));
      inputs.push_back(RawEncoding(1, 3, Raw({c.child(0), c.child(2)})));
      std::string trailing = three + std::string("\x01\x02\x03", 3);
      inputs.push_back(trailing);
      inputs.push_back(RawEncoding(1, 0, {}));
    }
    inputs.push_back(RawEncoding(1, 1, {0}));
    inputs.push_back(RawEncoding(1, 1, {0xd000000000000000ULL}));
    inputs.push_back(RawEncoding(1, 1, {0x1000000000000002ULL}));
    inputs.push_back(RawEncoding(1, 2, {0x3000000000000000ULL, 0x1000000000000000ULL}));
    {
      S2CellId c = RandCellAt(14);
      inputs.push_back(RawEncoding(1, 2, Raw({c, c})));
      inputs.push_back(RawEncoding(1, 2, Raw({c, c.child(3)})));
      inputs.push_back(RawEncoding(1, 2, Raw({c.child(3), c})));
    }
    for (int i = 0; i < 200; ++i) {
      int len = static_cast<int>(rng() % 41);
      std::string s;
      for (int k = 0; k < len; ++k) s.push_back(static_cast<char>(rng() & 0xff));
      // Bias the first bytes towards a plausible header, so some strings get past it.
      if (len > 0 && i % 2 == 0) s[0] = static_cast<char>(rng() % 3);
      if (len > 8 && i % 4 == 0) {
        for (int k = 2; k < 9; ++k) s[k] = 0;
        s[1] = static_cast<char>(rng() % 5);
      }
      inputs.push_back(s);
    }
    for (const std::string& bytes : inputs) {
      Decoder decoder(bytes.data(), bytes.size());
      S2CellUnion u;
      bool ok = u.Decode(&decoder);
      bool valid = ok && u.IsValid();
      std::printf("%s,%d,%d,%s\n", HexBytes(bytes).c_str(), ok ? 1 : 0, valid ? 1 : 0,
                  ok ? Ids(u.cell_ids()).c_str() : "");
    }
  }
  return 0;
}
